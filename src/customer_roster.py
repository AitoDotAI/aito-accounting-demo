"""The ids of the customers this deployment knows, for rejecting typos.

`data/customers.json` is generated by `./do fixtures`, not committed. A
deployment built without it has no roster, and then the unknown-customer
check cannot run. That is reported here, loudly, rather than hidden: the
check stays off (failing closed would reject every request), and
`/health` carries the roster size so a deploy can be gated on it.
"""

import json
import sys
from pathlib import Path


def load_roster(path: Path) -> set[str]:
    """Customer ids in `path`; an empty set, with a stderr message, if unreadable."""
    try:
        with open(path) as f:
            return {c["customer_id"] for c in json.load(f)}
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f"customer roster {path} unreadable ({type(exc).__name__}: {exc}): "
              f"customer_id validation is OFF -- any id is accepted. "
              f"Generate it with ./do fixtures.", file=sys.stderr)
        return set()


def roster_status(roster: set[str]) -> str:
    return "ok" if roster else "degraded"
